        private bool DetectSupportsEmbeddings()
        {
            // If the GGUF declares a pooling type (mean/cls/last/rank) it is authoritative:
            // llama.cpp only sets this for models that produce sentence-level embeddings.
            if (_Model?.Metadata != null &&
                _Model.Metadata.TryGetValue("general.pooling_type", out string pooling) &&
                !string.IsNullOrEmpty(pooling) && pooling != "-1" && pooling != "none")
            {
                return true;
            }

            string arch = Architecture;
            if (!string.IsNullOrEmpty(arch) && SharpAI.Helpers.GgufMetadataReader.EmbeddingOnlyArchitectures.Contains(arch))
            {
                return true;
            }

            return false;
        }

        private bool DetectSupportsGeneration()
        {
            string arch = Architecture;
            if (!string.IsNullOrEmpty(arch) && SharpAI.Helpers.GgufMetadataReader.EmbeddingOnlyArchitectures.Contains(arch))
            {
                return false;
            }

            // Default: any decoder-capable model (llama, qwen2, mistral, phi3, gemma, ...) supports generation.
            return true;
        }

        private async Task<float[]> ProcessTextWithChunking(string text, CancellationToken token)
        {
            if (string.IsNullOrWhiteSpace(text))
                throw new ArgumentException("Text cannot be null or empty", nameof(text));

            int contextSize = (int)(_EmbeddingModel?.ContextSize ?? 512);
            int tokenLimit = (int)(contextSize * 0.8);
            int charLimit = tokenLimit * 3;

            async Task<float[]> TryEmbed(string input)
            {
                await _EmbedderSemaphore.WaitAsync(token).ConfigureAwait(false);
                try
                {
                    return (await _Embedder.GetEmbeddings(input, token).ConfigureAwait(false)).Single();
                }
                finally
                {
                    _EmbedderSemaphore.Release();
                }
            }

            try
            {
                if (text.Length <= charLimit)
                {
                    return await TryEmbed(text).ConfigureAwait(false);
                }

                if (!_EnableEmbeddingChunking)
                {
                    throw new InvalidOperationException(
                        $"Embedding input of {text.Length} characters exceeds the model's context (~{charLimit} chars) and chunking is disabled. " +
                        "Shorten the input or enable EnableEmbeddingChunking to chunk and average.");
                }

                SharpAI.Logging.JsonLog.Debug(_Logging, _Header + $"processing long text ({text.Length} chars) in chunks (limit: {charLimit})");
                List<string> chunks = SplitTextIntoChunks(text, charLimit);
                List<float[]> embeddings = new List<float[]>();

                for (int index = 0; index < chunks.Count; index++)
                {
                    string chunk = chunks[index];
                    try
                    {
                        embeddings.Add(await TryEmbed(chunk).ConfigureAwait(false));
                    }
                    catch (ArgumentException ex) when (ex.Message.Contains("Embedding prompt is longer"))
                    {
                        SharpAI.Logging.JsonLog.Warn(_Logging, _Header + $"chunk {index + 1} too long after split, retrying with smaller chunks");
                        int retryLimit = charLimit / 2;
                        List<string> subChunks = SplitTextIntoChunks(chunk, retryLimit);
                        foreach (string subChunk in subChunks)
                        {
                            embeddings.Add(await TryEmbed(subChunk).ConfigureAwait(false));
                        }
                    }
                    catch (Exception ex)
                    {
                        SharpAI.Logging.JsonLog.Error(_Logging, _Header + $"failed to process chunk {index + 1}: {ex.Message}");
                        throw new InvalidOperationException($"Failed to process text chunk {index + 1}/{chunks.Count}: {ex.Message}", ex);
                    }
                }

                return AverageEmbeddings(embeddings);
            }
            catch (Exception ex)
            {
                SharpAI.Logging.JsonLog.Error(_Logging, _Header + "exception during fallback chunked embedding: " + ex.Message);
                throw;
            }
        }

        private List<string> SplitTextIntoChunks(string text, int maxCharacters)
        {
            List<string> chunks = new List<string>();
            int currentIndex = 0;

            while (currentIndex < text.Length)
            {
                int chunkSize = Math.Min(maxCharacters, text.Length - currentIndex);
                string chunk = text.Substring(currentIndex, chunkSize);

                if (currentIndex + chunkSize < text.Length && !char.IsWhiteSpace(text[currentIndex + chunkSize]))
                {
                    int lastSpaceIndex = chunk.LastIndexOf(' ');
                    if (lastSpaceIndex > chunkSize / 2)
                    {
                        chunk = chunk.Substring(0, lastSpaceIndex);
                        chunkSize = lastSpaceIndex;
                    }
                }

                chunks.Add(chunk.Trim());
                currentIndex += chunkSize;

                while (currentIndex < text.Length && char.IsWhiteSpace(text[currentIndex]))
                {
                    currentIndex++;
                }
            }

            SharpAI.Logging.JsonLog.Debug(_Logging, _Header + $"split text into {chunks.Count} chunks");
            return chunks;
        }

        private float[] AverageEmbeddings(List<float[]> embeddings)
        {
            if (embeddings == null || embeddings.Count == 0)
            {
                throw new ArgumentException("Embeddings list cannot be null or empty", nameof(embeddings));
            }

            if (embeddings.Count == 1)
            {
                return embeddings[0];
            }

            int dimensions = embeddings[0].Length;
            float[] averaged = new float[dimensions];

            foreach (float[] embedding in embeddings)
            {
                if (embedding.Length != dimensions)
                {
                    throw new InvalidOperationException("all embeddings must have the same dimensions");
                }

                for (int i = 0; i < dimensions; i++)
                {
                    averaged[i] += embedding[i];
                }
            }

            for (int i = 0; i < dimensions; i++)
            {
                averaged[i] /= embeddings.Count;
            }

            return averaged;
        }

        private void ThrowIfNotInitialized()
        {
            if (!_IsInitialized) throw new InvalidOperationException("Provider must be initialized before use. Call InitializeAsync() first.");
            if (_Disposed) throw new ObjectDisposedException(nameof(LlamaSharpEngine));
        }

        private string TelemetryModelLabel()
        {
            string arch = Architecture;
            if (!String.IsNullOrEmpty(arch)) return arch;
            if (!String.IsNullOrEmpty(ModelPath)) return Path.GetFileNameWithoutExtension(ModelPath);
            return "unknown";
        }

        private int EffectiveMaxTokens(int requested)
        {
            // Honor any positive request exactly, including small values (e.g. max_tokens=8). Only fall
            // back to the configured default when the caller did not specify a positive maximum.
            if (requested > 0) return requested;
            return _DefaultMaxTokens;
        }

        // LlamaSharp 0.30 creates and disposes a new inference context on every call.
        // Separate executors prevent concurrent mutation of its Context and batch fields.
        /// <summary>Snapshot of effective generation settings, rather than environment overrides.</summary>
        /// <returns>Settings after initialization.</returns>
        public Dictionary<string, object> GetRuntimeSettings()
        {
            ThrowIfNotInitialized();
            return new Dictionary<string, object>
            {
                { "context", GetContextSize() }, { "gpu_layers_requested", _GpuLayers },
                { "slots", _MaxConcurrentGenerations }, { "threads", _GenerationParams.Threads },
                { "batch_threads", _GenerationParams.BatchThreads }, { "batch_size", _GenerationParams.BatchSize },
                { "micro_batch_size", _GenerationParams.UBatchSize }, { "cache_k", _GenerationParams.TypeK?.ToString() ?? "F16" },
                { "cache_v", _GenerationParams.TypeV?.ToString() ?? "F16" }, { "flash_attention", _GenerationParams.FlashAttention },
                { "mmap", (_GenerationParams.LoadMode == LLamaLoadMode.MemoryMap || _GenerationParams.LoadMode == LLamaLoadMode.MemoryMapAndLock) }, { "mlock", (_GenerationParams.LoadMode == LLamaLoadMode.MemoryLock || _GenerationParams.LoadMode == LLamaLoadMode.MemoryMapAndLock) }
            };
        }

        /// <summary>Validate the exact rendered prompt and reserve the requested output within effective context.</summary>
        /// <param name="prompt">Rendered prompt.</param><param name="maxTokens">Requested output tokens.</param>
        public void ValidateContext(string prompt, int maxTokens)
        {
            ThrowIfNotInitialized();
            int count = _Context.Tokenize(prompt ?? String.Empty, true, true).Length;
            ContextLimitException.Validate(count, EffectiveMaxTokens(maxTokens), GetContextSize());
        }

        private async IAsyncEnumerable<string> GenerateMeasuredStreamAsync(string prompt, int maxTokens, float temperature,
            string[] stopSequences, string grammar, string operation, InferenceStatistics target,
            [EnumeratorCancellation] CancellationToken token, SharpAI.Models.Ollama.OllamaCompletionOptions sampling = null)
        {
            ThrowIfNotInitialized();
            ValidateContext(prompt, maxTokens);
            InferenceStatistics measured = new InferenceStatistics();
            measured.PromptTokens = _Context.Tokenize(prompt ?? String.Empty, true, true).Length;
            using Activity activity = SharpAITelemetry.StartInference(operation, TelemetryModelLabel());
            measured.CaptureTrace(activity);
            Stopwatch watch = Stopwatch.StartNew();
            bool acquired = false;
            bool success = false;
            try
            {
                await AcquireGenerationSlotAsync(token).ConfigureAwait(false);
                acquired = true;
                Interlocked.Increment(ref _ActiveGenerations);
                measured.QueueDurationNanoseconds = watch.Elapsed.Ticks * 100;
                SharpAITelemetry.ChangeBusySlots(TelemetryModelLabel(), 1);
                using MeasuredSamplingPipeline pipeline = new MeasuredSamplingPipeline((context, id) =>
                {
                    LLamaPerfContextTimings timings = context.GetTimings();
                    measured.PromptDurationNanoseconds = timings.PromptEval.Ticks * 100;
                    measured.GenerationDurationNanoseconds = timings.Eval.Ticks * 100;
                    if (!id.IsEndOfGeneration(_Model.Vocab))
                    {
                        measured.CompletionTokens++;
                        if (measured.FirstTokenDurationNanoseconds == 0) measured.FirstTokenDurationNanoseconds = watch.Elapsed.Ticks * 100;
                    }
                }, sampling) { Temperature = temperature, Grammar = grammar == null ? null : new LLama.Sampling.Grammar(grammar, SharpAI.Grammars.JsonGrammar.RootRule) };
                InferenceParams parameters = new InferenceParams
                {
                    MaxTokens = EffectiveMaxTokens(maxTokens),
                    AntiPrompts = stopSequences?.ToList() ?? (operation == "chat" ? new List<string> { "user:", "User:", "human:", "Human:" } : new List<string>()),
                    SamplingPipeline = pipeline,
                    OverflowStrategy = ContextOverflowStrategy.ThrowException
                };
                StatelessExecutor executor = CreateExecutorForCall();
                long promptWall = 0;
                long generationWall = 0;
                bool firstStep = true;
                await using (IAsyncEnumerator<string> sequence = executor.InferAsync(prompt ?? String.Empty, parameters, token).GetAsyncEnumerator(token))
                {
                    while (true)
                    {
                        Stopwatch step = Stopwatch.StartNew();
                        bool available = await sequence.MoveNextAsync().ConfigureAwait(false);
                        long duration = step.Elapsed.Ticks * 100;
                        if (firstStep) { promptWall = duration; firstStep = false; }
                        else generationWall += duration;
                        // Native performance counters may be disabled by the pinned backend. Wall intervals
                        // measure only backend steps; time spent consuming/yielding output is excluded.
                        if (measured.PromptDurationNanoseconds == 0 || measured.PhaseTimingsApproximate)
                        {
                            measured.PhaseTimingsApproximate = true;
                            measured.PromptDurationNanoseconds = promptWall;
                            measured.GenerationDurationNanoseconds = generationWall;
                        }
                        token.ThrowIfCancellationRequested();
                        if (!available) break;
                        yield return sequence.Current;
                        // Do not ask the backend to decode the last sampled token when the output
                        // budget is exhausted. That extra decode can overflow an exactly-full context.
                        if (measured.CompletionTokens >= parameters.MaxTokens) break;
                    }
                }
                token.ThrowIfCancellationRequested();
                success = true;
            }
            finally
            {
                measured.Cancelled = token.IsCancellationRequested;
                measured.TotalDurationNanoseconds = watch.Elapsed.Ticks * 100;
                if (!acquired) measured.QueueDurationNanoseconds = measured.TotalDurationNanoseconds;
                target?.Add(measured);
                if (acquired)
                {
                    Interlocked.Decrement(ref _ActiveGenerations);
                    _GenerationSemaphore.Release();
                    SharpAITelemetry.ChangeBusySlots(TelemetryModelLabel(), -1);
                }
                SharpAITelemetry.CompleteInference(activity, measured, success);
                // The rolling server log is tailed by the collector into Loki. Keep request text out.
                SharpAI.Logging.JsonLog.Info(_Logging, "[EngineOperation] " + SharpAITelemetry.FormatCompletion(activity, operation, TelemetryModelLabel(), measured, success));
                SharpAITelemetry.RecordDetails(TelemetryModelLabel(), measured);
                SharpAITelemetry.RecordInference(operation, TelemetryModelLabel(), watch.Elapsed.TotalSeconds, measured.CompletionTokens, success);
            }
        }

        private StatelessExecutor CreateExecutorForCall()
        {
            if (_MaxConcurrentGenerations <= 1) return _StatelessExecutor;
            return new StatelessExecutor(_Model, _GenerationParams);
        }

        // Build the sampling pipeline, optionally constrained by a GBNF grammar (JSON mode / structured
        // outputs). When gbnfGrammar is non-null the grammar limits which tokens may be sampled.
        private DefaultSamplingPipeline CreateSamplingPipeline(float temperature, string gbnfGrammar)
        {
            if (!String.IsNullOrEmpty(gbnfGrammar))
            {
                return new DefaultSamplingPipeline
                {
                    Temperature = temperature,
                    Grammar = new LLama.Sampling.Grammar(gbnfGrammar, SharpAI.Grammars.JsonGrammar.RootRule)
                };
            }

            return new DefaultSamplingPipeline
            {
                Temperature = temperature
            };
        }

        private async Task AcquireGenerationSlotAsync(CancellationToken token)
        {
            if (_GenerationQueueTimeoutMs <= 0)
            {
                // Zero/negative timeout means "wait forever" (bounded only by cancellation). Wait on the
                // semaphore directly; a recursive self-call here would overflow the stack.
                await _GenerationSemaphore.WaitAsync(token).ConfigureAwait(false);
                return;
            }

            bool acquired = await _GenerationSemaphore.WaitAsync(_GenerationQueueTimeoutMs, token).ConfigureAwait(false);
            if (!acquired)
                throw new SharpAI.Exceptions.EngineBusyException(
                    $"All {_MaxConcurrentGenerations} generation slot(s) are busy; timed out after {_GenerationQueueTimeoutMs} ms.");
        }

        private async Task EnsureEmbedderAsync(CancellationToken token)
        {
            if (_Embedder != null) return;

            await _EmbedderInitSemaphore.WaitAsync(token).ConfigureAwait(false);
            try
            {
                if (_Embedder != null) return;

                if (_EmbedderLoadAttempted)
                    throw new InvalidOperationException("Embeddings are not supported. The embedder failed to initialize.");

                _EmbedderLoadAttempted = true;

                await Task.Run(() =>
                {
                    ModelParams embeddingParams = CreateModelParams(ModelPath, _GpuLayers, true, false);
                    _EmbeddingModel = LLamaWeights.LoadFromFile(embeddingParams);
                    _Embedder = new LLamaEmbedder(_EmbeddingModel, embeddingParams);
                }, token).ConfigureAwait(false);

                SharpAI.Logging.JsonLog.Debug(_Logging, _Header + "embedding model loaded on demand");
            }
            catch (Exception ex)
            {
                SharpAI.Logging.JsonLog.Warn(_Logging, _Header + "failed to initialize embeddings:" + Environment.NewLine + ex.ToString());

                try { _Embedder?.Dispose(); } catch { }
                try { _EmbeddingModel?.Dispose(); } catch { }
                _Embedder = null;
                _EmbeddingModel = null;

                throw new InvalidOperationException("Embeddings are not supported. The embedder failed to initialize.", ex);
            }
            finally
            {
                _EmbedderInitSemaphore.Release();
            }
        }

