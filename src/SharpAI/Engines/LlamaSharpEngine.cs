        /// <summary>
        /// Releases all resources used by the LlamaSharpEngine.
        /// Properly disposes of the model, context, and embedder instances.
        /// </summary>
        public override void Dispose()
        {
            if (_Disposed) return;

            try
            {
                _ChatSession = null;
                _Executor = null;
                _StatelessExecutor = null;

                _Embedder?.Dispose();
                _EmbeddingModel?.Dispose();
                _Context?.Dispose();
                _Model?.Dispose();

                _EmbedderSemaphore?.Dispose();
                _EmbedderInitSemaphore?.Dispose();
                _GenerationSemaphore?.Dispose();
            }
            catch (Exception ex)
            {
                SharpAI.Logging.JsonLog.Warn(_Logging, _Header + "disposal exception:" + Environment.NewLine + ex.ToString());
            }
            finally
            {
                _Disposed = true;
            SharpAITelemetry.RemoveSlots(TelemetryModelLabel());
                _IsInitialized = false;
            }
        }

