        private bool DetectSupportsEmbeddings()
        {
            // If the GGUF declares a pooling type (mean/cls/last/rank) it is authoritative:
            // llama.cpp only sets this for models that produce sentence-level embeddings.
            if (_Model?.Metadata != null &&
                _Model.Metadata.TryGetValue("general.pooling_type", out string pooling) &&
                !string.IsNullOrEmpty(pooling) && pooling != "-1" && pooling != "none")
            {
                return true;
            }

            string arch = Architecture;
            if (!string.IsNullOrEmpty(arch) && SharpAI.Helpers.GgufMetadataReader.EmbeddingOnlyArchitectures.Contains(arch))
            {
                return true;
            }

            return false;
        }

        private bool DetectSupportsGeneration()
        {
            string arch = Architecture;
            if (!string.IsNullOrEmpty(arch) && SharpAI.Helpers.GgufMetadataReader.EmbeddingOnlyArchitectures.Contains(arch))
            {
                return false;
            }

            // Default: any decoder-capable model (llama, qwen2, mistral, phi3, gemma, ...) supports generation.
            return true;
        }

        private async Task<float[]> ProcessTextWithChunking(string text, CancellationToken token)
        {
            if (string.IsNullOrWhiteSpace(text))
                throw new ArgumentException("Text cannot be null or empty", nameof(text));

            int contextSize = (int)(_EmbeddingModel?.ContextSize ?? 512);
            int tokenLimit = (int)(contextSize * 0.8);
            int charLimit = tokenLimit * 3;

            async Task<float[]> TryEmbed(string input)
            {
                await _EmbedderSemaphore.WaitAsync(token).ConfigureAwait(false);
                try
                {
                    return (await _Embedder.GetEmbeddings(input, token).ConfigureAwait(false)).Single();
                }
                finally
                {
                    _EmbedderSemaphore.Release();
                }
            }

            try
            {
                if (text.Length <= charLimit)
                {
                    return await TryEmbed(text).ConfigureAwait(false);
                }

                if (!_EnableEmbeddingChunking)
                {
                    throw new InvalidOperationException(
                        $"Embedding input of {text.Length} characters exceeds the model's context (~{charLimit} chars) and chunking is disabled. " +
                        "Shorten the input or enable EnableEmbeddingChunking to chunk and average.");
                }

                _Logging?.Debug(_Header + $"processing long text ({text.Length} chars) in chunks (limit: {charLimit})");
                List<string> chunks = SplitTextIntoChunks(text, charLimit);
                List<float[]> embeddings = new List<float[]>();

                foreach ((string chunk, int index) in chunks.Select((c, i) => (c, i)))
                {
                    try
                    {
                        embeddings.Add(await TryEmbed(chunk).ConfigureAwait(false));
                    }
                    catch (ArgumentException ex) when (ex.Message.Contains("Embedding prompt is longer"))
                    {
                        _Logging?.Warn(_Header + $"chunk {index + 1} too long after split, retrying with smaller chunks");
                        int retryLimit = charLimit / 2;
                        List<string> subChunks = SplitTextIntoChunks(chunk, retryLimit);
                        foreach (string subChunk in subChunks)
                        {
                            embeddings.Add(await TryEmbed(subChunk).ConfigureAwait(false));
                        }
                    }
                    catch (Exception ex)
                    {
                        _Logging?.Error(_Header + $"failed to process chunk {index + 1}: {ex.Message}");
                        throw new InvalidOperationException($"Failed to process text chunk {index + 1}/{chunks.Count}: {ex.Message}", ex);
                    }
                }

                return AverageEmbeddings(embeddings);
            }
            catch (Exception ex)
            {
                _Logging?.Error(_Header + "exception during fallback chunked embedding: " + ex.Message);
                throw;
            }
        }

        private List<string> SplitTextIntoChunks(string text, int maxCharacters)
        {
            List<string> chunks = new List<string>();
            int currentIndex = 0;

            while (currentIndex < text.Length)
            {
                int chunkSize = Math.Min(maxCharacters, text.Length - currentIndex);
                string chunk = text.Substring(currentIndex, chunkSize);

                if (currentIndex + chunkSize < text.Length && !char.IsWhiteSpace(text[currentIndex + chunkSize]))
                {
                    int lastSpaceIndex = chunk.LastIndexOf(' ');
                    if (lastSpaceIndex > chunkSize / 2)
                    {
                        chunk = chunk.Substring(0, lastSpaceIndex);
                        chunkSize = lastSpaceIndex;
                    }
                }

                chunks.Add(chunk.Trim());
                currentIndex += chunkSize;

                while (currentIndex < text.Length && char.IsWhiteSpace(text[currentIndex]))
                {
                    currentIndex++;
                }
            }

            _Logging?.Debug(_Header + $"split text into {chunks.Count} chunks");
            return chunks;
        }

        private float[] AverageEmbeddings(List<float[]> embeddings)
        {
            if (embeddings == null || embeddings.Count == 0)
            {
                throw new ArgumentException("Embeddings list cannot be null or empty", nameof(embeddings));
            }

            if (embeddings.Count == 1)
            {
                return embeddings[0];
            }

            int dimensions = embeddings[0].Length;
            float[] averaged = new float[dimensions];

            foreach (float[] embedding in embeddings)
            {
                if (embedding.Length != dimensions)
                {
                    throw new InvalidOperationException("all embeddings must have the same dimensions");
                }

                for (int i = 0; i < dimensions; i++)
                {
                    averaged[i] += embedding[i];
                }
            }

            for (int i = 0; i < dimensions; i++)
            {
                averaged[i] /= embeddings.Count;
            }

            return averaged;
        }

        private void ThrowIfNotInitialized()
        {
            if (!_IsInitialized) throw new InvalidOperationException("Provider must be initialized before use. Call InitializeAsync() first.");
            if (_Disposed) throw new ObjectDisposedException(nameof(LlamaSharpEngine));
        }

        private string TelemetryModelLabel()
        {
            string arch = Architecture;
            if (!String.IsNullOrEmpty(arch)) return arch;
            if (!String.IsNullOrEmpty(ModelPath)) return Path.GetFileNameWithoutExtension(ModelPath);
            return "unknown";
        }

        private int EffectiveMaxTokens(int requested)
        {
            // Honor any positive request exactly, including small values (e.g. max_tokens=8). Only fall
            // back to the configured default when the caller did not specify a positive maximum.
            if (requested > 0) return requested;
            return _DefaultMaxTokens;
        }

        // Return the StatelessExecutor to use for a single generation. The shared executor caches an internal
        // context across calls, so it is only safe when generations are serialized (one slot). When more than
        // one concurrent generation slot is configured, hand each call its own executor (hence its own
        // context/KV-cache) to avoid the concurrent calls racing on — and disposing — a shared context.
        private StatelessExecutor CreateExecutorForCall()
        {
            if (_MaxConcurrentGenerations <= 1) return _StatelessExecutor;
            return new StatelessExecutor(_Model, _GenerationParams);
        }

        // Build the sampling pipeline, optionally constrained by a GBNF grammar (JSON mode / structured
        // outputs). When gbnfGrammar is non-null the grammar limits which tokens may be sampled.
        private DefaultSamplingPipeline CreateSamplingPipeline(float temperature, string gbnfGrammar)
        {
            if (!String.IsNullOrEmpty(gbnfGrammar))
            {
                return new DefaultSamplingPipeline
                {
                    Temperature = temperature,
                    Grammar = new LLama.Sampling.Grammar(gbnfGrammar, SharpAI.Grammars.JsonGrammar.RootRule)
                };
            }

            return new DefaultSamplingPipeline
            {
                Temperature = temperature
            };
        }

        private async Task AcquireGenerationSlotAsync(CancellationToken token)
        {
            if (_GenerationQueueTimeoutMs <= 0)
            {
                // Zero/negative timeout means "wait forever" (bounded only by cancellation). Wait on the
                // semaphore directly; a recursive self-call here would overflow the stack.
                await _GenerationSemaphore.WaitAsync(token).ConfigureAwait(false);
                return;
            }

            bool acquired = await _GenerationSemaphore.WaitAsync(_GenerationQueueTimeoutMs, token).ConfigureAwait(false);
            if (!acquired)
                throw new SharpAI.Exceptions.EngineBusyException(
                    $"All {_MaxConcurrentGenerations} generation slot(s) are busy; timed out after {_GenerationQueueTimeoutMs} ms.");
        }

        private async Task EnsureEmbedderAsync(CancellationToken token)
        {
            if (_Embedder != null) return;

            await _EmbedderInitSemaphore.WaitAsync(token).ConfigureAwait(false);
            try
            {
                if (_Embedder != null) return;

                if (_EmbedderLoadAttempted)
                    throw new InvalidOperationException("Embeddings are not supported. The embedder failed to initialize.");

                _EmbedderLoadAttempted = true;

                await Task.Run(() =>
                {
                    ModelParams embeddingParams = CreateModelParams(ModelPath, _GpuLayers, true, false);
                    _EmbeddingModel = LLamaWeights.LoadFromFile(embeddingParams);
                    _Embedder = new LLamaEmbedder(_EmbeddingModel, embeddingParams);
                }, token).ConfigureAwait(false);

                _Logging.Debug(_Header + "embedding model loaded on demand");
            }
            catch (Exception ex)
            {
                _Logging.Warn(_Header + "failed to initialize embeddings:" + Environment.NewLine + ex.ToString());

                try { _Embedder?.Dispose(); } catch { }
                try { _EmbeddingModel?.Dispose(); } catch { }
                _Embedder = null;
                _EmbeddingModel = null;

                throw new InvalidOperationException("Embeddings are not supported. The embedder failed to initialize.", ex);
            }
            finally
            {
                _EmbedderInitSemaphore.Release();
            }
        }

