        /// <summary>
        /// Initializes the LlamaSharp engine with the specified model file.
        /// Loads the model, creates context, and sets up executors for text generation and embeddings.
        /// </summary>
        /// <param name="modelPath">The file path to the GGUF model file to load.</param>
        /// <returns>A task that represents the asynchronous initialization operation.</returns>
        /// <exception cref="Exception">Thrown when the model fails to load or initialize.</exception>
        public override async Task InitializeAsync(string modelPath)
        {
            if (_IsInitialized) return;

            ModelPath = modelPath;
            using Activity loadActivity = SharpAITelemetry.Source.StartActivity("model.load", ActivityKind.Internal);
            loadActivity?.SetTag("sharpai.model", Path.GetFileName(modelPath));
            Stopwatch loadWatch = Stopwatch.StartNew();

            await Task.Run(() =>
            {
                try
                {
                    int gpuLayers = GetOptimalGpuLayers();
                    SharpAI.Logging.JsonLog.Debug(_Logging, _Header + $"initializing LlamaSharp with {(gpuLayers != 0 ? $"GPU ({gpuLayers} layers requested)" : "CPU")}");

                    ModelParams parameters = CreateModelParams(modelPath, gpuLayers, false, true);

                    _Model = LLamaWeights.LoadFromFile(parameters);
                    _Context = _Model.CreateContext(parameters);
                    _GenerationParams = parameters;

                    _Executor = new InteractiveExecutor(_Context); // text generation
                    _StatelessExecutor = new StatelessExecutor(_Model, parameters); // text generation
                    _ChatSession = new ChatSession(_Executor);

                    // Embeddings load lazily on first use (see EnsureEmbedderAsync). A generation-only
                    // model never allocates the second copy of the weights that a dedicated embedding
                    // context requires.
                    _GpuLayers = gpuLayers;

                    // Concurrency and admission configuration (env overrides the property defaults).
                    _MaxConcurrentGenerations = SharpAIEnvironment.GetInt(SharpAIEnvironment.MaxConcurrentGenerations, _MaxConcurrentGenerations, 1);
                    _GenerationQueueTimeoutMs = SharpAIEnvironment.GetInt(SharpAIEnvironment.GenerationQueueTimeoutMs, _GenerationQueueTimeoutMs, 0);
                    if (_MaxConcurrentGenerations > 1)
                    {
                        _GenerationSemaphore.Dispose();
                        _GenerationSemaphore = new SemaphoreSlim(_MaxConcurrentGenerations, _MaxConcurrentGenerations);
                    }
                    SharpAI.Logging.JsonLog.Debug(_Logging, _Header + $"generation slots={_MaxConcurrentGenerations}, queueTimeoutMs={_GenerationQueueTimeoutMs}");

                    _IsInitialized = true;
                    LoadDurationNanoseconds = loadWatch.Elapsed.Ticks * 100;
                    SharpAITelemetry.RecordLoad(TelemetryModelLabel(), loadWatch.Elapsed.TotalSeconds, _MaxConcurrentGenerations);
                    loadActivity?.SetTag("sharpai.load_duration_ns", LoadDurationNanoseconds);
                    loadActivity?.SetTag("sharpai.slots", _MaxConcurrentGenerations);
                    loadActivity?.SetStatus(ActivityStatusCode.Ok);
                    SharpAI.Logging.JsonLog.Info(_Logging, "[EngineOperation] " + System.Text.Json.JsonSerializer.Serialize(new
                    {
                        event_name = "engine.model.loaded", model = TelemetryModelLabel(),
                        trace_id = loadActivity?.TraceId.ToHexString(), span_id = loadActivity?.SpanId.ToHexString(),
                        load_duration_ns = LoadDurationNanoseconds, slots = _MaxConcurrentGenerations,
                        backend = NativeBackendInfo.SelectedBackend
                    }));

                    SharpAI.Logging.JsonLog.Debug(_Logging, _Header + "LlamaSharp provider initialized successfully");
                }
                catch (Exception ex)
                {
                    loadActivity?.SetStatus(ActivityStatusCode.Error);
                    throw new Exception("failed to initialize LlamaSharp:" + Environment.NewLine + ex.ToString());
                }
            });
        }

        /// <summary>
        /// Determines the optimal number of GPU layers to use based on available hardware.
        /// </summary>
        /// <returns>Zero for CPU, a configured positive layer count, or 999 to request all model layers. Native loading clamps this request to the model's layer count.</returns>
        /// <remarks>Initializes the library backend once per process before choosing layers. Initialization failures propagate to the caller.</remarks>
        public override int GetOptimalGpuLayers()
        {
            NativeBackendInitializer.Initialize(_Logging);
            try
            {
                // Initialization belongs to the library and preserves any explicit host selection.
                string selectedBackend = SharpAI.Classes.Runtime.NativeBackendInfo.SelectedBackend;

                if (selectedBackend.Equals("cuda", StringComparison.OrdinalIgnoreCase)
                    || selectedBackend.Equals("metal", StringComparison.OrdinalIgnoreCase))
                {
                    long gpuDeviceCount = LLama.Native.NativeApi.llama_max_devices();
                    SharpAI.Logging.JsonLog.Debug(_Logging, _Header + $"{selectedBackend} backend selected, {gpuDeviceCount} GPU device(s) available");

                    string configuredGpuLayers = SharpAIEnvironment.GetString(SharpAIEnvironment.GpuLayers);
                    if (!String.IsNullOrEmpty(configuredGpuLayers)
                        && !configuredGpuLayers.Equals("auto", StringComparison.OrdinalIgnoreCase))
                    {
                        if (Int32.TryParse(configuredGpuLayers, out int parsedGpuLayers) && parsedGpuLayers >= -1)
                        {
                            if (parsedGpuLayers == -1)
                            {
                                SharpAI.Logging.JsonLog.Debug(_Logging, _Header + "GPU layer override requests all layers");
                                return 999;
                            }

                            SharpAI.Logging.JsonLog.Debug(_Logging, _Header + $"GPU layer override requests {parsedGpuLayers} layer(s)");
                            return parsedGpuLayers;
                        }

                        SharpAI.Logging.JsonLog.Warn(_Logging, _Header + $"{SharpAIEnvironment.GpuLayers} value '" + configuredGpuLayers + "' is invalid, using automatic GPU layer selection");
                    }

                    return 999; // big positive -> clamp to all layers
                }
                else
                {
                    SharpAI.Logging.JsonLog.Debug(_Logging, _Header + $"{selectedBackend} backend selected, using CPU");
                    return 0;
                }
            }
            catch (Exception ex)
            {
                SharpAI.Logging.JsonLog.Debug(_Logging, _Header + "GPU detection exception, using CPU:" + Environment.NewLine + ex.ToString());
                return 0;
            }
        }

