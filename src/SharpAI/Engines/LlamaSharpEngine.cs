            StringBuilder output = new StringBuilder();
            await foreach (string text in GenerateMeasuredStreamAsync(prompt, maxTokens, temperature, stopSequences,
                gbnfGrammar, "completion", statistics, token, sampling).ConfigureAwait(false)) output.Append(text);
            return output.ToString().Trim();
        }

